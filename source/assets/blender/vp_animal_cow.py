def teats(bm):
    for sx in (-1, 1):
        for sy in (-1, 1):
            c = V(sx * 0.06, 0.55 + sy * 0.065, 0.585)
            bm = merge(bm, loft([c + V(0, 0, 0.05), c, c + V(0, 0, -0.045)], [0.02, 0.014, 0.011], segs=8, res=2))
    return bm


