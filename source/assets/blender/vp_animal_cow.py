def patch(p):
    f = fbm(V(p.x * 0.9, p.y * 0.7, p.z * 1.1), 1.5, 3, 11)
    return sstep(-0.02, 0.07, f)


def coat(p, n):
    blk = patch(p)
    blk *= 1.0 - sstep(0.90, 0.72, p.z) * 0.9      # white belly
    blk *= 1.0 - sstep(0.62, 0.45, p.z)            # white socks
    c = mixc(W, K, blk)
    if p.y > 0.3 and 0.5 < p.z < 0.88 and abs(p.x) < 0.14 and n.z < 0.3:
        c = mixc(c, PINK, sstep(0.0, 0.1, p.y - 0.2) * sstep(0.88, 0.8, p.z))
    k = 0.9 + 0.14 * (fbm(p, 14, 2, 3) * 0.5 + 0.5)
    if p.z < 0.2:
        c = mixc(c, '#8a7c66', 0.35 * sstep(0.2, 0.0, p.z))
    return mulc(c, k)


def headcol(p, n, q, uu):
    c = K
    blaze = sstep(0.05, 0.02, abs(p.x)) * sstep(-0.05, 0.05, uu + 0.02)
    c = mixc(c, W, blaze * (1 - sstep(0.30, 0.38, q)))
    c = mixc(c, '#c99d93', sstep(0.36, 0.44, q))
    c = mixc(c, '#d9c9bd', sstep(-0.02, -0.07, uu) * 0.45)
    return mulc(c, 0.92 + 0.12 * (fbm(p, 40, 2, 3) * .5 + .5))


def earcol(p, n, inner, t):
    return mixc('#d4a79c', '#7a5a52', t * 0.4) if inner else K


